import pandas as pd # Импортируем библиотеку для удобной работы с табличными данными и даем ей псевдоним
import matplotlib.pyplot as plt # Импортируем модуль для создания графиков и даем ему псевдоним  
import statsmodels.api as sm # Модуль для статистического моделирования, включая доступ к различным наборам данных

# 1. Загрузка данных из statsmodels
try: # начинаем блок, который обрабатывает ошибки во время выполнения кода 
    data = sm.datasets.elnino.load_pandas().data # загрудаем набор данных El Nino из statsmodels
except Exception as e: # Eсли  возникли ошибки, переходим в этот блок 
    print(f"Ошибка при загрузке данных: {e}") # Выводит сообщение об ошибке
    exit()  # Завершаем выполнение, если не удалось загрузить данные

# 2. Преобразование индекса и выбор периода времени
# Попытка автоматического определения столбца с информацией о времени
if 'YEAR' in data.columns:  # Проверяем существует ли столбец с именем YEAR
    # Преобразуем в datetime, если это необходимо
    data['YEAR'] = pd.to_datetime(data['YEAR'], format='%Y')
    # Устанавливаем 'YEAR' как индекс
    data = data.set_index('YEAR')
    # Выбор данных за период 1990-2010
    data = data['1990':'2010']  # Срез по индексу datetime
elif 'time' in data.columns: #  Проверяет, существует ли столбец с именем 'time' в DataFrame
    #Если индекс это просто числа (time)
    data = data[(data['time'] >= 1990) & (data['time'] <= 2010)] #Создает фильтр для DataFrame, отбирая только те строки, 
    #в которых значения в столбце time больше или равны 1990 и меньше или равны 2010.  
    #Этот метод используется, когда time содержит числовые значения.

    data = data.set_index('time') #Делаем столбец time индексом DataFrame
else:
    print("Не найдена колонка с информацией о времени (YEAR или time).  Укажите колонку времени явно, если она существует.")
    exit()  # Завершаем выполнение, если не нашли колонку времени

# 3. Обработка пропущенных значений (заполнение средним значением)
data = data.fillna(data.mean())  # Заполняем NaN средним значением по столбцу

# 4. Визуализация всех временных рядов
for column in data.columns: # Перебираем каждый столбец табицы
    # Создаем новый график для каждого временного ряда, увеличиваем размер
    plt.figure(figsize=(14, 7))
    # Строим график
    plt.plot(data[column])

    # Настройка графика
    plt.xlabel("Время", fontsize=12)  # Подпись оси X
    # Подпись оси Y (используем имя столбца)
    plt.ylabel(column, fontsize=12)
    # Заголовок графика
    plt.title(f"Временной ряд: {column} (1990-2010)", fontsize=14)
    # Добавляем сетку для удобства чтения
    plt.grid(True, linestyle='--', alpha=0.6)
    # Поворачиваем подписи оси X для лучшей читаемости, если это год
    plt.xticks(rotation=45)
    # Улучшает расположение элементов графика
    plt.tight_layout()
    # Отображаем график
    plt.show()

print("Графики временных рядов построены.")